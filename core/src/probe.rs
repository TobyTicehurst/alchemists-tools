//! Probe mods: UE4SS logging hooks for game functions, to find out what calls them and with what.
//!
//! Functions are given as `<Class>:<Function>`, with the class as in the C++ headers without its
//! U/A prefix (`BeltTDInventoryComponent`) and `*` or `?` allowed in the function. Parameter names
//! and types come from UE4SS's header dump (`ue4ss/UHTHeaderDump`), and struct layouts from the
//! `.usmap`, so the log shows each argument's contents. A Blueprint function is given by its full
//! path (`/Game/.../BP_X.BP_X_C:Function`); its arguments are logged without names.
//!
//! A probe is a mod folder (`mod.json`, `ue4ss/Scripts/main.lua`) that needs the AlchemistsLibrary
//! mod, which is written to the mods folder too if it isn't there.

use std::path::{Path, PathBuf};

use anyhow::{bail, Result};
use serde_json::{json, Value};

use crate::game::{display_path, join, Game};
use crate::schema::{Property, Schemas};

const TEMPLATE: &str = include_str!("../../ue4ss/probe.lua");
const LIBRARY_MOD: &str = include_str!("../../ue4ss/AlchemistsLibrary/mod.json");
const LIBRARY: &str = include_str!(
    "../../ue4ss/AlchemistsLibrary/ue4ss-shared/AlchemistsLibrary/AlchemistsLibrary.lua"
);
const GENERATED: &str = "-- Generated by alchemists-tools probe";
const GENERATED_BEFORE: &str = "-- Generated by tools/make_probe.py";

/// Every `.h` file below `folder`.
fn headers(folder: &Path) -> Vec<PathBuf> {
    let mut out = vec![];
    let mut todo = vec![folder.to_path_buf()];
    while let Some(current) = todo.pop() {
        for entry in std::fs::read_dir(&current).into_iter().flatten().flatten() {
            let path = entry.path();
            if path.is_dir() {
                todo.push(path);
            } else if path.extension().is_some_and(|extension| extension == "h") {
                out.push(path);
            }
        }
    }
    out.sort();
    out
}

/// (module, header text) of the C++ class `U<name>`/`A<name>`/`F<name>`: a definition, not a
/// forward declaration.
fn find_class(dump: &Path, name: &str) -> Result<(String, String)> {
    for path in headers(dump) {
        let Ok(text) = std::fs::read_to_string(&path) else {
            continue;
        };
        let defines = text.lines().any(|line| {
            let Some(rest) = line.strip_prefix("class ") else {
                return false;
            };
            let mut words = rest.split_whitespace();
            let mut word = words.next().unwrap_or_default();
            if word.ends_with("_API") {
                word = words.next().unwrap_or_default();
            }
            let after = words.next().unwrap_or_default();
            let class = word.trim_end_matches([':', '{']);
            class.len() == name.len() + 1
                && class[1..] == *name
                && class.starts_with(['U', 'A', 'F'])
                && (word.ends_with([':', '{']) || after.starts_with([':', '{']))
        });
        if defines {
            let module = path
                .strip_prefix(dump)
                .ok()
                .and_then(|p| p.components().next())
                .map(|c| c.as_os_str().to_string_lossy().into_owned());
            return Ok((module.unwrap_or_default(), text));
        }
    }
    bail!(
        "no class {name} in {} (dump the headers with UE4SS, or check the name)",
        display_path(dump)
    )
}

/// Split a parameter list at commas outside `<>` and `()`.
fn split_top_level(text: &str) -> Vec<String> {
    let (mut parts, mut depth, mut current) = (vec![], 0, String::new());
    for c in text.chars() {
        match c {
            '<' | '(' => depth += 1,
            '>' | ')' => depth -= 1,
            _ => {}
        }
        if c == ',' && depth == 0 {
            parts.push(std::mem::take(&mut current));
        } else {
            current.push(c);
        }
    }
    parts.push(current);
    parts
        .into_iter()
        .map(|part| part.trim().to_string())
        .filter(|part| !part.is_empty())
        .collect()
}

/// The UFUNCTIONs a header declares: (name, [(type, parameter name)]).
fn functions(text: &str) -> Vec<(String, Vec<(String, String)>)> {
    let mut out = vec![];
    let mut rest = text;
    while let Some(at) = rest.find("UFUNCTION(") {
        rest = &rest[at + "UFUNCTION(".len()..];
        // the macro's own (balanced) parentheses
        let mut depth = 1;
        let mut end = 0;
        for (i, c) in rest.char_indices() {
            match c {
                '(' => depth += 1,
                ')' => depth -= 1,
                _ => {}
            }
            if depth == 0 {
                end = i + 1;
                break;
            }
        }
        rest = &rest[end..];
        let Some(stop) = rest.find([';', '{']) else {
            break;
        };
        let declaration = rest[..stop]
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ");
        let declaration = declaration.trim().trim_end_matches("const").trim();
        let (Some(open), Some(close)) = (declaration.find('('), declaration.rfind(')')) else {
            continue;
        };
        let name = declaration[..open]
            .trim()
            .rsplit([' ', '*', '&'])
            .next()
            .unwrap_or_default()
            .to_string();
        let parameters = split_top_level(&declaration[open + 1..close])
            .into_iter()
            .filter_map(|parameter| {
                let parameter = parameter
                    .split('=')
                    .next()
                    .unwrap_or_default()
                    .trim()
                    .to_string();
                let split = parameter.rfind(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))?;
                Some((
                    parameter[..=split].trim().to_string(),
                    parameter[split + 1..].to_string(),
                ))
            })
            .collect();
        if !name.is_empty() {
            out.push((name, parameters));
        }
    }
    out
}

/// `*` and `?` wildcards.
fn matches(pattern: &str, text: &str) -> bool {
    match (pattern.chars().next(), text.chars().next()) {
        (None, None) => true,
        (Some('*'), _) => {
            matches(&pattern[1..], text)
                || (!text.is_empty()
                    && matches(pattern, &text[text.chars().next().unwrap().len_utf8()..]))
        }
        (Some('?'), Some(c)) => matches(&pattern[1..], &text[c.len_utf8()..]),
        (Some(p), Some(c)) if p == c => matches(&pattern[p.len_utf8()..], &text[c.len_utf8()..]),
        _ => false,
    }
}

/// What the library's `describe` needs to show a value of this C++ type (None for plain values
/// and objects).
fn layout(cpp_type: &str, schemas: &Schemas, depth: usize) -> Option<Value> {
    let bare = cpp_type.replace("const ", "").replace(['&', '*'], "");
    let bare = bare.trim();
    for container in ["TArray<", "TSet<"] {
        if let Some(inner) = bare
            .strip_prefix(container)
            .and_then(|inner| inner.strip_suffix('>'))
        {
            return Some(
                json!({"array": layout(inner.trim(), schemas, depth + 1).unwrap_or(json!({}))}),
            );
        }
    }
    let struct_name = bare.strip_prefix('F')?;
    if depth >= 3
        || ["Name", "String", "Text"].contains(&struct_name)
        || !schemas.structs.contains_key(struct_name)
    {
        return None;
    }
    struct_layout(struct_name, schemas, depth)
}

fn struct_layout(name: &str, schemas: &Schemas, depth: usize) -> Option<Value> {
    let mut fields = vec![];
    let mut seen = vec![];
    for (property, _) in schemas.all_properties(name).ok()? {
        if seen.contains(&&property.name) {
            continue;
        }
        seen.push(&property.name);
        let mut field = json!({"name": property.name});
        if let Some(inner) = property_layout(property, schemas, depth + 1) {
            field["layout"] = inner;
        }
        fields.push(field);
    }
    Some(json!({"fields": fields}))
}

fn property_layout(property: &Property, schemas: &Schemas, depth: usize) -> Option<Value> {
    if depth >= 3 {
        return None;
    }
    match property.type_name.as_str() {
        "Struct" => struct_layout(property.struct_name.as_deref()?, schemas, depth),
        "Array" | "Set" => {
            let inner = property
                .inner
                .as_deref()
                .and_then(|inner| property_layout(inner, schemas, depth + 1));
            Some(json!({"array": inner.unwrap_or(json!({}))}))
        }
        _ => None,
    }
}

/// A JSON value as a Lua table constructor.
fn lua(value: &Value) -> String {
    match value {
        Value::Object(object) => {
            let parts: Vec<String> = object
                .iter()
                .map(|(key, value)| format!("{key} = {}", lua(value)))
                .collect();
            format!("{{{}}}", parts.join(", "))
        }
        Value::Array(items) => format!(
            "{{{}}}",
            items.iter().map(lua).collect::<Vec<_>>().join(", ")
        ),
        Value::Null => "nil".into(),
        other => other.to_string(),
    }
}

/// Git Bash turns `/Game/...` and `/Script/...` arguments into Windows paths; take them back.
pub fn unmangle(path: &str) -> String {
    let path = path.replace('\\', "/");
    for prefix in ["/Game/", "/Script/"] {
        if let Some(at) = path.find(prefix).filter(|&at| at > 0) {
            return path[at..].to_string();
        }
    }
    path
}

/// Write the probe mod `<mods>/<name>/` (and the AlchemistsLibrary mod if it isn't there).
#[allow(clippy::too_many_arguments)]
pub fn write_probe(
    game: &Game,
    schemas: &Schemas,
    mods: &Path,
    name: &str,
    functions_wanted: &[String],
    new_objects: &[String],
    limit: usize,
    force: bool,
) -> Result<PathBuf> {
    if !(name.chars().next().is_some_and(|c| c.is_ascii_alphabetic())
        && name.chars().all(|c| c.is_ascii_alphanumeric()))
    {
        bail!("a mod name is letters and digits, starting with a letter");
    }
    if functions_wanted.is_empty() && new_objects.is_empty() {
        bail!("give functions to hook, or classes to watch for new objects");
    }
    let dump = join(
        &game.root,
        &[
            "AlchemyFactory",
            "Binaries",
            "Win64",
            "ue4ss",
            "UHTHeaderDump",
        ],
    );
    let mut hooks = vec![];
    for wanted in functions_wanted {
        let wanted = unmangle(wanted);
        let Some((owner, pattern)) = wanted.rsplit_once(':') else {
            bail!("{wanted}: give <Class>:<Function>");
        };
        if owner.starts_with('/') {
            hooks.push(json!({"path": wanted})); // a Blueprint function: no header to read
            continue;
        }
        let (module, text) = find_class(&dump, owner)?;
        let declared = functions(&text);
        let mut found: Vec<&(String, Vec<(String, String)>)> = declared
            .iter()
            .filter(|(function, _)| matches(pattern, function))
            .collect();
        found.sort_by(|a, b| a.0.cmp(&b.0));
        if found.is_empty() {
            let mut names: Vec<&str> = declared
                .iter()
                .map(|(function, _)| function.as_str())
                .collect();
            names.sort();
            bail!(
                "{wanted}: no such function; {owner} declares {}",
                names.join(", ")
            );
        }
        for (function, parameters) in found {
            let params: Vec<Value> = parameters
                .iter()
                .map(|(cpp_type, parameter)| {
                    let mut entry = json!({"name": parameter, "type": cpp_type});
                    if let Some(found) = layout(cpp_type, schemas, 0) {
                        entry["layout"] = found;
                    }
                    entry
                })
                .collect();
            let shown: Vec<String> = parameters.iter().map(|(t, p)| format!("{t} {p}")).collect();
            println!("{module}.{owner}:{function}({})", shown.join(", "));
            hooks.push(
                json!({"path": format!("/Script/{module}.{owner}:{function}"), "params": params}),
            );
        }
    }
    let new_objects: Vec<String> = new_objects.iter().map(|class| unmangle(class)).collect();
    for class in &new_objects {
        println!("new objects of {class}");
    }

    let folder = mods.join(name);
    let script = join(&folder, &["ue4ss", "Scripts", "main.lua"]);
    if folder.exists() && !force {
        bail!("{} exists (--force to overwrite it)", display_path(&folder));
    }
    if let Ok(existing) = std::fs::read_to_string(&script) {
        if !existing.starts_with(GENERATED) && !existing.starts_with(GENERATED_BEFORE) {
            bail!(
                "{} wasn't written as a probe; not overwriting it",
                display_path(&script)
            );
        }
    }
    let mut command: Vec<String> = functions_wanted.to_vec();
    command.extend(
        new_objects
            .iter()
            .map(|class| format!("--new-object {class}")),
    );
    let text = TEMPLATE
        .replace("@COMMAND@", &format!("{name} {}", command.join(" ")))
        .replace("@NAME@", name)
        .replace("@LIMIT@", &limit.to_string())
        .replace("@HOOKS@", &lua(&Value::Array(hooks)))
        .replace("@NEW_OBJECTS@", &lua(&json!(new_objects)));
    std::fs::create_dir_all(script.parent().unwrap())?;
    std::fs::write(&script, text)?;

    // The library, at least the version the probe was written for (its functions may be new)
    let library: Value = serde_json::from_str(LIBRARY_MOD)?;
    let version = library["version"].as_str().unwrap_or("0.1.0").to_string();
    let library_folder = mods.join("AlchemistsLibrary");
    if !library_folder.join("mod.json").exists() {
        let module = join(&library_folder, &["ue4ss-shared", "AlchemistsLibrary"]);
        std::fs::create_dir_all(&module)?;
        std::fs::write(library_folder.join("mod.json"), LIBRARY_MOD)?;
        std::fs::write(module.join("AlchemistsLibrary.lua"), LIBRARY)?;
        println!(
            "wrote {} (the library probes need)",
            display_path(&library_folder)
        );
    }
    let description = format!(
        "Logs calls to {}{}. Changes nothing.",
        if functions_wanted.is_empty() {
            "nothing".to_string()
        } else {
            functions_wanted.join(", ")
        },
        if new_objects.is_empty() {
            String::new()
        } else {
            format!(" and new {}", new_objects.join(", "))
        }
    );
    let manifest = json!({
        "name": name,
        "title": format!("{name} (probe)"),
        "version": "0.1.0",
        "description": description,
        "dependencies": [format!("AlchemistsLibrary >= {version}")],
    });
    std::fs::write(
        folder.join("mod.json"),
        serde_json::to_string_pretty(&manifest)? + "\n",
    )?;
    println!(
        "wrote {}: alchemists-tools mod install {name} --with-dependencies",
        display_path(&folder)
    );
    Ok(folder)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn declarations() {
        let header =
            "class BELTTD_API UThing : public UObject {\n    UFUNCTION(BlueprintCallable, \
            meta=(WorldContext=\"W\"))\n    \
                      bool CheckCanCost(const TArray<FBeltTDIngredientCount>& IngredientList, \
                          int32 Count = 1) const;\n    \
                      UFUNCTION(BlueprintCallable)\n    void Server_AddItem(const FVector& occurs, \
                          FName ItemName);\n};";
        let found = functions(header);
        assert_eq!(found[0].0, "CheckCanCost");
        assert_eq!(
            found[0].1,
            [
                (
                    "const TArray<FBeltTDIngredientCount>&".to_string(),
                    "IngredientList".to_string()
                ),
                ("int32".to_string(), "Count".to_string())
            ]
        );
        assert_eq!(found[1].1[1], ("FName".to_string(), "ItemName".to_string()));
    }

    #[test]
    fn wildcards() {
        assert!(matches("Server_*", "Server_AddItem"));
        assert!(matches("Check?anCost", "CheckCanCost"));
        assert!(!matches("Server_*", "CheckCanCost"));
    }

    #[test]
    fn paths() {
        assert_eq!(
            unmangle("C:/Program Files/Git/Game/Blueprints/X.X_C"),
            "/Game/Blueprints/X.X_C"
        );
        assert_eq!(unmangle("/Game/X"), "/Game/X");
    }
}
